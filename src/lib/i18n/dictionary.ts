/** Plain integer, Arabic-Indic digits (٠١٢...) in Arabic, Western in English.
 * Use for quantities people read as numbers — prices, mileage, years, counts.
 * Do NOT use for stock/order codes or phone numbers — those stay Western
 * numerals in both languages, same convention Saudi systems use for them. */
/**
 * `value` is typed as `number` but isn't always one in practice — cars
 * submitted through the separate seller app that shares this Supabase
 * project can land with null price/mileage/etc. (its submission form
 * doesn't collect them), and that reaches the admin panel once a pending
 * listing is visible there. Never throw on that; show a placeholder.
 */
export function formatNumber(value: number, locale: Locale = "en", fractionDigits = 0): string {
  if (!Number.isFinite(value)) return "—";
  return value.toLocaleString(locale === "ar" ? "ar-SA" : "en-US", {
    minimumFractionDigits: fractionDigits,
    maximumFractionDigits: fractionDigits,
  });
}

export function formatSar(value: number, locale: Locale = "en"): string {
  if (!Number.isFinite(value)) return "—";
  const amount = formatNumber(value, locale);
  return locale === "ar" ? `${amount} ريال` : `SAR ${amount}`;
}
